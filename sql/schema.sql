CREATE SCHEMA IF NOT EXISTS SUPPLYGUARD;

CREATE TABLE IF NOT EXISTS SUPPLYGUARD.DEMAND_HISTORY (
    PART_ID VARCHAR(50),
    WEEK_DATE DATE,
    DEMAND INTEGER,
    UNIT_PRICE DOUBLE,
    PROMOTION INTEGER,
    LEAD_TIME_DAYS INTEGER,
    SUPPLIER_ID VARCHAR(50),
    SUPPLIER_RELIABILITY DOUBLE,
    INVENTORY_LEVEL INTEGER
);

CREATE TABLE IF NOT EXISTS SUPPLYGUARD.FORECAST_RESULTS (
    PART_ID VARCHAR(50),
    FORECAST_WEEK INTEGER,
    FORECAST_DATE DATE,
    PREDICTED_DEMAND DOUBLE,
    STOCKOUT_RISK VARCHAR(20),
    RECOMMENDED_STOCK INTEGER
);

CREATE TABLE IF NOT EXISTS SUPPLYGUARD.SUPPLIER_RISK (
    SUPPLIER_ID VARCHAR(50),
    SUPPLIER_RELIABILITY DOUBLE,
    AVERAGE_LEAD_TIME DOUBLE,
    RISK_SCORE DOUBLE,
    RISK_LEVEL VARCHAR(20)
);